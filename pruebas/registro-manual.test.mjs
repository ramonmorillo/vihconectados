import test from 'node:test';
import assert from 'node:assert/strict';
import { crearPaciente, vacio, anexar } from '../src/almacen.js';
import { cobertura, componentes, importarCSV, prepararDispensacionManual, alertas, REGLAS } from '../src/motor.js';
import { ficha, normalizarFicha, modalidadTar } from '../src/cima.js';
import { ultimaEvaluacionAdherencia } from '../src/adherencia.js';
import { informe, resumenInforme, textoInforme } from '../src/informes.js';
import { vistaInforme } from '../src/vista-informes.js';
import { fichaPrueba } from './fixtures-cima.js';
const cfg={...REGLAS,ventana:90};
const med=(id,inyectable=false)=>{
 const {presentaciones,...m}=normalizarFicha({...fichaPrueba,nregistro:id,nombre:'TAR SINTÉTICO '+id,viasAdministracion:[{nombre:inyectable?'VÍA INTRAMUSCULAR':'VÍA ORAL'}]});
 return {...m,cn:id,presentacion:presentaciones[0].nombre};
};
const tratamiento=(ms,fecha='2026-01-01')=>({tipo:'tratamiento',tar:'CIMA',fecha,medicamentos:ms,modalidad:modalidadTar(ms),confirmado:true});
const inicial=()=>anexar(crearPaciente(vacio()),'DEMO-001',tratamiento([med('999991'),med('999992')]));
const evaluacion=(extra={})=>({tipo:'evaluacion_adherencia',fecha:'2026-01-31',periodo_inicio:'2026-01-01',periodo_fin:'2026-01-31',metodo:'Autoinforme',resultado:'No concluyente',porcentaje:null,...extra});
test('CIMA intramuscular requiere aceptación explícita y conserva ambos medicamentos; no admite mezcla de fases',async()=>{
 const respuesta=async()=>({ok:true,json:async()=>({...fichaPrueba,viasAdministracion:[{nombre:'VÍA INTRAMUSCULAR'}]})});
 await assert.rejects(()=>ficha('999999',respuesta),/no permite confirmar/);
 const f=await ficha('999999',respuesta,{permitirInyectable:true});
 assert.equal(f.intramuscular,true); assert.equal(f.oral,false);
 let d=anexar(crearPaciente(vacio()),'DEMO-001',tratamiento([med('999993',true),med('999994',true)]));
 assert.equal(d.pacientes[0].eventos.at(-1).medicamentos.length,2);
 assert.equal(d.pacientes[0].eventos.at(-1).modalidad,'inyectable');
 assert.throws(()=>modalidadTar([med('999991'),med('999993',true)]),/No mezcle/);
 assert.throws(()=>anexar(crearPaciente(vacio()),'DEMO-001',{...tratamiento([med('999993',true)]),modalidad:'oral'}),/incompleto/);
 assert.throws(()=>anexar(crearPaciente(vacio()),'DEMO-001',tratamiento([med('999993',true),med('999993',true)])),/repetirse/);
});
test('TAR inyectable no crea falso PDC cero, alertas de baja cobertura ni días de suministro',()=>{
 const d=anexar(crearPaciente(vacio()),'DEMO-001',tratamiento([med('999993',true),med('999994',true)])),p=d.pacientes[0],ep=p.eventos.at(-1);
 const c=cobertura(p,'2026-01-31',cfg);
 assert.equal(c.pdc,null);assert.equal(c.total,0);assert.equal(c.excluidos[0].total,30);
 assert.deepEqual(componentes(ep),[]);
 assert.deepEqual(alertas(p,'2026-01-31',cfg).map(a=>a.regla),['tar_inyectable_no_evaluable']);
 assert.throws(()=>importarCSV(p,`fecha;episodio;componente;dias\n2026-01-01;${ep.id};CIMA-999993;30`),/incompatibles/);
 assert.throws(()=>prepararDispensacionManual(p,{fecha:'2026-01-01',episodio:ep.id,suministros:[{componente:'CIMA-999993',dias:30}]}),/episodio oral/);
 assert.match(textoInforme(informe(p,'2026-01-31',cfg)),/periodos excluidos/);
 assert.match(vistaInforme(informe(p,'2026-01-31',cfg)),/periodos excluidos/);
});
test('Cambio oral a inyectable excluye solo el intervalo inyectable y corta sobrantes',()=>{
 let d=inicial(),p=d.pacientes[0],ep=p.eventos.at(-1);
 const r=prepararDispensacionManual(p,{fecha:'2026-01-01',episodio:ep.id,suministros:[{componente:'CIMA-999991',dias:90},{componente:'CIMA-999992',dias:90}]});
 d=anexar(d,p.id,{tipo:'importacion',fuente:'Entrada manual',...r});
 d=anexar(d,p.id,tratamiento([med('999993',true),med('999994',true)],'2026-01-11'));
 const c=cobertura(d.pacientes[0],'2026-01-31',cfg);
 assert.equal(c.total,10); assert.equal(c.cubiertos,10);assert.equal(c.pdc,1);assert.equal(c.excluidos[0].total,20);
 d=anexar(d,p.id,tratamiento([med('999991'),med('999992')],'2026-01-21'));
 const vuelta=cobertura(d.pacientes[0],'2026-01-31',cfg);
 assert.equal(vuelta.total,20);assert.equal(vuelta.cubiertos,10);assert.equal(vuelta.excluidos[0].total,10);
});
test('Dispensación manual multicomponente comparte deduplicación y conflictos con CSV de forma atómica',()=>{
 let d=inicial(),p=d.pacientes[0],ep=p.eventos.at(-1);
 const entrada={fecha:'2026-01-01',episodio:ep.id,suministros:[{componente:'CIMA-999991',dias:30},{componente:'CIMA-999992',dias:10}]};
 const r=prepararDispensacionManual(p,entrada);
 d=anexar(d,p.id,{tipo:'importacion',fuente:'Entrada manual',...r});p=d.pacientes[0];
 assert.equal(cobertura(p,'2026-01-31',cfg).cubiertos,10);
 assert.equal(prepararDispensacionManual(p,entrada).filas.length,0);
 assert.equal(importarCSV(p,`fecha;episodio;componente;dias\n2026-01-01;${ep.id};CIMA-999991;30`).duplicadas.length,1);
 const antes=JSON.stringify(d);
 assert.throws(()=>prepararDispensacionManual(p,{...entrada,suministros:[entrada.suministros[0],{componente:'CIMA-999992',dias:20}]}),/conflicto/);
 assert.equal(JSON.stringify(d),antes);
 assert.throws(()=>anexar(d,p.id,{tipo:'importacion',fuente:'Entrada manual',...r}),/duplicado/);
 for (const dias of [0,-1,401,1.5,NaN,'30']) assert.throws(()=>prepararDispensacionManual(p,{...entrada,suministros:[{componente:'CIMA-999991',dias}]}));
 assert.throws(()=>prepararDispensacionManual(p,{...entrada,fecha:'2025-12-31'}),/incompatibles/);
 assert.throws(()=>prepararDispensacionManual(p,{...entrada,suministros:[entrada.suministros[0],entrada.suministros[0]]}),/repetido/);
});
test('Valoración manual valida método, periodo y porcentaje; cero y sin estimar son distintos',()=>{
 const d=inicial(),id=d.pacientes[0].id;
 for (const porcentaje of [0,100,85.5,null]) assert.doesNotThrow(()=>anexar(d,id,evaluacion({porcentaje})));
 for (const porcentaje of [-1,101,NaN,Infinity,'80',undefined]) assert.throws(()=>anexar(d,id,evaluacion({porcentaje})),/porcentaje/);
 for (const extra of [{periodo_inicio:'2026-01-31'},{periodo_fin:'2026-02-01'},{fecha:'2026-01-30'},{periodo_inicio:'2026-02-30'},{metodo:'Automático'},{resultado:'Adherente confirmado'}]) assert.throws(()=>anexar(d,id,evaluacion(extra)));
});
test('Adherencia manual conserva histórico, respeta corte y no altera PDC, alertas o informes previos',()=>{
 let d=inicial(),p=d.pacientes[0],c=cobertura(p,'2026-01-31',cfg),a=alertas(p,'2026-01-31',cfg);
 const previo=informe(p,'2026-01-31',cfg),jsonPrevio=JSON.stringify(previo);
 d=anexar(d,p.id,evaluacion({porcentaje:80}));
 const manual=d.pacientes[0].eventos.at(-1);
 d=anexar(d,p.id,evaluacion({fecha:'2026-02-01',porcentaje:90}));
 p=d.pacientes[0];
 assert.deepEqual(cobertura(p,'2026-01-31',cfg),c);assert.deepEqual(alertas(p,'2026-01-31',cfg),a);
 assert.equal(ultimaEvaluacionAdherencia(p,'2026-01-31').id,manual.id);
 assert.equal(ultimaEvaluacionAdherencia(p,'2025-12-31'),undefined);
 const i=informe(p,'2026-01-31',cfg);
 assert.equal(resumenInforme(i).evaluacion_adherencia.porcentaje,80);
 assert.match(textoInforme(i),/80 % declarado/);assert.match(vistaInforme(i),/80 % declarado/);
 assert.doesNotMatch(textoInforme(previo),/80 % declarado/);assert.equal(JSON.stringify(previo),jsonPrevio);
 d=anexar(d,p.id,evaluacion({porcentaje:0}));
 assert.match(textoInforme(informe(d.pacientes[0],'2026-01-31',cfg)),/0 % declarado/);
});
